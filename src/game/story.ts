/**
 * 节点类型。
 *
 * ⚠️ 相比上一版，`auto` / `boss` 合并成了 `battle` —— 因为剧情战斗**不再挂在主线关卡上**
 * （用户 2026-09-22：「剧情的战斗不和主线战斗耦合」）。既然是自己的战斗，
 * 它就只需要一份 `combat` 规格，不需要知道"这相当于主线的第几关"，
 * `boss` 在数据上也就没有区别了（它只是 `combat.count` 更大、`power` 更高的一场）。
 */
