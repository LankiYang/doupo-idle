// ─── ⑤ 剧情对话 ─────────────────────────────────────────────────────────

export interface ScriptLine {
  /** 说话人显示名。空串 = 旁白（组件渲染成无名卡、不挂立绘） */
  who: string
  /** 身份注脚。**只在人物第一次说话时给**，后面留空 —— 每句都挂身份会变成说明书 */
  role?: string
  /** 立绘 id（见 `vnPortrait.ts`）。给了就出场/切人；不给 = 沿用上一位说话人的站位 */
  speaker?: string
  /** 站位。给了 `speaker` 时必给；只换站位不换人也可以单给 */
  side?: SpeakerSide
  /** `exit: true` = 这一句说完，这个人**退场**（淡出） */
  exit?: boolean
  /** 场景图，只在该行切场景时才给；不给 = 沿用上一行 */
  scene?: SceneId
  text: string
}

